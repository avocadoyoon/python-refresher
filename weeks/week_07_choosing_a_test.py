# Notes
# The basic rule:
# 2 independent groups → t-test
# 3+ independent groups → ANOVA

# Correlation ≠ group comparison.

# Categorical variable + categorical variable → chi-square

# Did speech rate change after therapy?
# Groups are not independent, and same people appear twice, so we would use a paired sampled t-test.

## SOME TERMS I MIGHT NEED
    #   1. Outcome/dependent variable: the variable that is being predicted or explained.
    #   2. Predictor/independent variable: the variable that is being used to predict or explain the outcome variable.
    #   3. Control variable: a variable that is held constant or accounted for in order to isolate the effect of the predictor variable on the outcome variable.    
    #   4. Grouping variable: a variable that is used to categorize or group the data into different levels or categories for analysis.
    #   5. p-value: How compatible are the observed data with the null hypothesis?
    #   6. Effect size: Okay, but HOW BIG is the difference/relationship?
        # Cohen's d, r, R², standardized coefficients


